"""Generate configs and submit script for Batch 1 experiments.

Usage:
    python scripts/experiments/prepare_batch1.py

Generates:
    results/batch1/{1_baseline,2_batch250,...}/config.toml
    results/batch1/submit_batch1.sh

Then submit all at once:
    bash results/batch1/submit_batch1.sh
"""

from __future__ import annotations

from pathlib import Path

from gen_config import generate_config

_SCRIPT = Path(__file__).resolve()
SCRIPTS_DIR = _SCRIPT.parent
REPO_ROOT = SCRIPTS_DIR.parent.parent
BASE_CONFIG = REPO_ROOT / "config.toml"
BATCH_NAME = "batch1"
BATCH_DIR = REPO_ROOT / "results" / BATCH_NAME

# Each experiment: (run_name, description, override_dict)
EXPERIMENTS: list[tuple[str, str, dict]] = [
    (
        "1_baseline",
        "batch=500, emitters=4, sigma0=0.3",
        {
            "archive.dims": [20, 20, 20],
            "archive.ranges": [[1.0, 6.0], [0.0, 0.7], [50.0, 600.0]],
            "archive.dimension_names": ["br_sascore", "ad", "mw"],
            "archive.dimension_enabled": [True, True, True],
            "archive.learning_rate": 0.1,
            "emitter.sigma0": 0.3,
            "emitter.batch_size": 500,
            "emitter.n_emitters": 4,
            "run.n_generations": 300,
            "run.eval_every": 10,
            "run.seed": 42,
            "output.output_dir": "results/batch1",
            "output.run_name": "1_baseline",
            "generative.n_seeds": 2500,
            "generative.seed": 42,
        },
    ),
    (
        "2_batch250",
        "batch=250, emitters=4 → 1000 mols/gen",
        {
            "emitter.batch_size": 250,
            "output.run_name": "2_batch250",
        },
    ),
    (
        "3_batch1000",
        "batch=1000, emitters=4 → 4000 mols/gen",
        {
            "emitter.batch_size": 1000,
            "output.run_name": "3_batch1000",
        },
    ),
    (
        "4_emitters2",
        "batch=1000, emitters=2 → 2000 mols/gen (same as baseline)",
        {
            "emitter.batch_size": 1000,
            "emitter.n_emitters": 2,
            "output.run_name": "4_emitters2",
        },
    ),
    (
        "5_emitters8",
        "batch=250, emitters=8 → 2000 mols/gen (same as baseline)",
        {
            "emitter.batch_size": 250,
            "emitter.n_emitters": 8,
            "output.run_name": "5_emitters8",
        },
    ),
    (
        "6_sigma06",
        "sigma0=0.6, batch=500, emitters=4",
        {
            "emitter.sigma0": 0.6,
            "output.run_name": "6_sigma06",
        },
    ),
]


def _rel(path: Path) -> str:
    """Return *path* as relative to REPO_ROOT (for Slurm portability)."""
    return str(path.relative_to(REPO_ROOT))


def main() -> None:
    BATCH_DIR.mkdir(parents=True, exist_ok=True)

    submit_path = BATCH_DIR / "submit_batch1.sh"

    # All paths in the submit script are relative to REPO_ROOT so they work
    # regardless of whether the repo lives at /home/user/EVA or
    # /temporario2/15402906/EVA.
    slurm_rel = _rel(SCRIPTS_DIR / "run_eva.slurm")

    with open(submit_path, "w") as f:
        f.write("#!/bin/bash\n")
        f.write(f"# Submit all {len(EXPERIMENTS)} {BATCH_NAME} experiments\n")
        f.write(f"# Generated by {_SCRIPT}\n\n")
        f.write(f"JOB_IDS=()\n\n")

        for run_name, description, overrides in EXPERIMENTS:
            run_dir = BATCH_DIR / run_name
            config_path = run_dir / "config.toml"
            config_rel = _rel(config_path)
            out_rel = f"results/{BATCH_NAME}/{run_name}/slurm-%j.out"

            generate_config(BASE_CONFIG, overrides, config_path)
            print(f"  ✓ {run_name:20s}  {config_rel}")

            f.write(f'# {description}\n')
            f.write(
                f'JOB_ID=$(sbatch --parsable '
                f'--job-name="eva-{run_name}" '
                f'-o "{out_rel}" '
                f'{slurm_rel} {config_rel})\n'
            )
            f.write(f'echo "  Submitted {run_name} → $JOB_ID"\n')
            f.write(f'JOB_IDS+=($JOB_ID)\n\n')

        f.write('echo "\\nAll submitted. Job IDs: ${JOB_IDS[*]}"\n')

    submit_path.chmod(0o755)
    print(f"\n  ✓ Submit script → {submit_path}")
    print(f"\n  To submit from repo root:  bash {_rel(submit_path)}")


if __name__ == "__main__":
    main()
